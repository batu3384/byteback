import { app, BrowserWindow } from 'electron'
import { join } from 'path'

// Load native addon
const nativePath = join(__dirname, '../../native/build/Release/wolf_engine.node')
// eslint-disable-next-line @typescript-eslint/no-var-requires
const wolfEngine = require(nativePath)

console.log('Wolf Engine version:', wolfEngine.getVersion())
console.log('Running as admin:', wolfEngine.isAdministrator())

let mainWindow: BrowserWindow | null = null

function createWindow(): void {
  mainWindow = new BrowserWindow({
    width: 1280,
    height: 800,
    minWidth: 1024,
    minHeight: 680,
    title: 'Wolf Recovery',
    backgroundColor: '#0D1117',
    show: false,
    webPreferences: {
      preload: join(__dirname, '../preload/preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false
    }
  })

  mainWindow.on('ready-to-show', () => {
    mainWindow?.show()
  })

  if (process.env.ELECTRON_RENDERER_URL) {
    mainWindow.loadURL(process.env.ELECTRON_RENDERER_URL)
  } else {
    mainWindow.loadFile(join(__dirname, '../renderer/index.html'))
  }
}

app.whenReady().then(createWindow)

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') {
    app.quit()
  }
})

app.on('activate', () => {
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow()
  }
})
